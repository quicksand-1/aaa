export const flatBookmarks = Object.values(bookmarksByCategory).flat();

export const getBookmarksByGroup = (group = '') =>
  bookmarksByCategory.env.filter((item) => item.group === group);

export const normalizeBookmarkText = (value = '') =>
  String(value)
    .toLowerCase()
    .replace(/\s+/g, '')
    .replace(/[【】\[\]()（）:：,，.。/\-_?#&=]+/g, '');

export const tokenizeBookmarkQuery = (value = '') => {
  const tokenMatches = String(value)
    .toLowerCase()
    .match(/[a-z0-9]+|[\u4e00-\u9fa5]+/g);

  return Array.from(new Set(tokenMatches || []));
};

export const buildBookmarkSearchText = (item = {}) =>
  [item.name, item.category, item.group, item.link, item.tip]
    .filter(Boolean)
    .join(' ');

export const scoreBookmark = (question = '', item = {}) => {
  const normalizedQuestion = normalizeBookmarkText(question);
  const normalizedName = normalizeBookmarkText(item.name);
  const normalizedGroup = normalizeBookmarkText(item.group);
  const normalizedCategory = normalizeBookmarkText(item.category);
  const normalizedLink = normalizeBookmarkText(item.link);
  const tokens = tokenizeBookmarkQuery(question);
  let score = 0;

  if (!normalizedQuestion) {
    return 0;
  }

  if (normalizedQuestion.includes(normalizedName)) {
    score += 10;
  }

  if (normalizedGroup && normalizedQuestion.includes(normalizedGroup)) {
    score += 6;
  }

  if (normalizedCategory && normalizedQuestion.includes(normalizedCategory)) {
    score += 3;
  }

  if (normalizedQuestion.includes(normalizedLink)) {
    score += 12;
  }

  const searchText = normalizeBookmarkText(buildBookmarkSearchText(item));
  tokens.forEach((token) => {
    const normalizedToken = normalizeBookmarkText(token);

    if (!normalizedToken) {
      return;
    }

    if (normalizedName.includes(normalizedToken)) {
      score += 4;
      return;
    }

    if (normalizedGroup && normalizedGroup.includes(normalizedToken)) {
      score += 3;
      return;
    }

    if (searchText.includes(normalizedToken)) {
      score += 1;
    }
  });

  return score;
};

export const findRelevantBookmarks = (question = '', limit = 5) =>
  flatBookmarks
    .map((item) => ({
      ...item,
      score: scoreBookmark(question, item),
    }))
    .filter((item) => item.score > 0)
    .sort((a, b) => {
      if (b.score !== a.score) {
        return b.score - a.score;
      }

      return a.name.localeCompare(b.name, 'zh-CN');
    })
    .slice(0, limit)
    .map(({ score, ...item }) => item);

export const buildBookmarkContext = () =>
  flatBookmarks
    .map((item) => {
      const parts = [
        `分类：${item.category}`,
        item.group ? `分组：${item.group}` : '',
        `名称：${item.name}`,
        `地址：${item.link}`,
        item.tip ? `备注：${item.tip}` : '',
      ].filter(Boolean);

      return `- ${parts.join(' | ')}`;
    })
    .join('\n');
